--
-- โจทย์ (พี่เจ้าของแจ้ง 2026-09-09): งานซีรีส์ต่างประเทศมีหลายบท ลูกค้าคอนเฟิร์ม
-- ไปแล้วหลายบท เหลือบทเดียวที่อยากขอดูตัวเลือกเพิ่ม → ต้องส่งลิงก์ที่เห็น
-- "เฉพาะบทนั้น" ไม่ให้สับสนกับบทที่ปิดไปแล้ว
--
-- เก็บไว้ที่ลิงก์ ไม่ใช่ query string เพราะ (1) ลูกค้าแก้ URL แล้วเห็นบทอื่นไม่ได้
-- (2) หนึ่งงานมีหลายลิงก์ แต่ละใบคุมคนละบทได้ (3) แอดมินเห็นชัดว่าลิงก์ไหน
-- คุมบทอะไร กันส่งผิดใบ
--
-- null / [] = โชว์ทุกบท → ลิงก์เก่าทั้งหมดทำงานเหมือนเดิม ไม่ต้องแก้อะไร
